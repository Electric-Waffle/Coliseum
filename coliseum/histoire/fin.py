    def DoLastFight(self):
        #lance un combat avec certains prerequis
        services.Player.affronte_fin_histoire = True
        control = controleur.Control(services.Player, services.Trader, services.FloorMaker, services.Sove)
        # lance la bataille
        while True:
            try:
                audio.CHANNELMUSIQUEDEBASE.set_volume(0)
                time.sleep(0.01)
                audio.CHANNELMUSIQUEDEBASE.stop()
                control.Battle()
                services.Player.affronte_fin_histoire = False
                StopAllMusic()
                self.PrintEtEntreePourContinuer("[COMBAT TERMINE]")
                break
            except Exception as error:
                WriteErrorInErrorLog(error)

